-- ============================================================
-- 新人業務考題抽選器：資料庫結構（Supabase / Postgres）
--
-- 怎麼執行：
--   1. 打開 Supabase 專案 → 左側 SQL Editor → New query
--   2. 把這整個檔案內容貼上 → 按 Run
--   3. 接著再執行 set_password.sql 設定管理密碼
--   4. 若是從舊版（題目是一段文字）升級：schema.sql 跑完後，
--      再執行本機的 migrate_tizu.local.sql（一次性遷移並匯入題組內容）
--
-- 這版起：一「題」是一個題組＝分類＋代號＋題組名稱＋步驟清單
-- （每個步驟有「考官操作」與「考點」）。分類為 基礎／進階／綜合。
-- 題組內容（考官操作、考點）不在本檔，因為本倉庫是公開的；
-- 內容只放在本機的 *.local.* 檔，由 migrate_tizu.local.sql 匯入。
-- 本檔在空資料庫上執行不會產生任何題目。
--
-- 可重複執行：資料表用 if not exists、函式用 create or replace，
-- 舊簽名函式會先 drop，所以重跑不會報錯，也不會動到既有的密碼、題目與已抽記錄。
--
-- 安全設計：資料表全部啟用 RLS 且不開放任何權限給網頁端（anon），
-- 前端只能呼叫下面的函式（RPC）。查分類、抽題、管理共用同一組密碼，
-- 並且在資料庫端檢查（密碼錯誤丟 invalid_password，不會有任何寫入）。
-- ============================================================

create extension if not exists pgcrypto with schema extensions;

-- ---------- 資料表 ----------

-- 題庫（題組）
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  category text not null check (length(btrim(category)) > 0),
  code text,
  title text,
  steps jsonb,
  created_at timestamptz default now()
);

-- 從舊版（單一 text 欄位）升級：補新欄位。
-- 升級中途 title／steps 保持可為 null（舊資料還沒遷移），由函式負責驗證；
-- migrate_tizu.local.sql 遷移完成後才會設為 not null。
alter table public.questions
  add column if not exists code text,
  add column if not exists title text,
  add column if not exists steps jsonb;

-- 舊的 text 欄位改為可為 null（若存在才處理）
do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'questions' and column_name = 'text') then
    alter table public.questions alter column "text" drop not null;
  end if;
end
$$;

-- steps 若不為 null 必須是 jsonb 陣列
do $$
begin
  if not exists (select 1 from pg_constraint
                 where conrelid = 'public.questions'::regclass and conname = 'questions_steps_is_array') then
    alter table public.questions
      add constraint questions_steps_is_array
      check (steps is null or jsonb_typeof(steps) = 'array');
  end if;
end
$$;

-- 本輪已抽的題目（所有裝置共用）
create table if not exists public.drawn (
  question_id bigint primary key references public.questions(id) on delete cascade,
  drawn_at timestamptz default now()
);

-- 每個分類最近一次抽出的題（新一輪第一題要避開它）
create table if not exists public.category_last (
  category text primary key,
  question_id bigint
);

-- 管理密碼雜湊（只會有一列）
create table if not exists public.app_secret (
  id int primary key check (id = 1),
  pw_hash text not null
);

-- 全部啟用 RLS，不建任何 policy，並收回所有人的直接存取權
alter table public.questions     enable row level security;
alter table public.drawn         enable row level security;
alter table public.category_last enable row level security;
alter table public.app_secret    enable row level security;

revoke all on table public.questions     from public, anon, authenticated;
revoke all on table public.drawn         from public, anon, authenticated;
revoke all on table public.category_last from public, anon, authenticated;
revoke all on table public.app_secret    from public, anon, authenticated;
revoke all on sequence public.questions_id_seq from public, anon, authenticated;

-- ---------- 內部小工具：密碼檢查（不開放給前端直接呼叫） ----------

-- 回傳密碼是否正確；尚未設密碼（app_secret 沒資料）一律視為錯誤
create or replace function public._pw_ok(p_pw text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select exists (
    select 1 from public.app_secret s
    where s.id = 1 and s.pw_hash = crypt(p_pw, s.pw_hash)
  );
$$;

-- 密碼錯誤就延遲 0.5 秒（拖慢暴力猜測）後丟 invalid_password
create or replace function public._assert_pw(p_pw text)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if not public._pw_ok(p_pw) then
    perform pg_sleep(0.5);
    raise exception 'invalid_password';
  end if;
end;
$$;

revoke execute on function public._pw_ok(text)     from public, anon, authenticated;
revoke execute on function public._assert_pw(text) from public, anon, authenticated;

-- ---------- 查分類與抽題（需要密碼） ----------

-- 舊版（免密碼）簽名的函式要先刪掉，否則會殘留且任何人都能免密碼呼叫
drop function if exists public.list_categories();
drop function if exists public.draw_questions(text[]);
-- 這版回傳欄位／簽名改變，也要先刪掉舊的
drop function if exists public.list_categories(text);
drop function if exists public.draw_questions(text, text[]);
drop function if exists public.admin_list_questions(text);
drop function if exists public.admin_save_question(text, bigint, text, text);

-- 各分類題數與本輪剩餘題數
create or replace function public.list_categories(p_pw text)
returns table(category text, total int, remaining int)
language plpgsql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
#variable_conflict use_column
begin
  perform public._assert_pw(p_pw);
  return query
    select q.category,
           count(*)::int,
           (count(*) - count(d.question_id))::int
    from public.questions q
    left join public.drawn d on d.question_id = q.id
    group by q.category
    order by min(q.id);
end;
$$;

-- 依序每個分類各抽 1 題
create or replace function public.draw_questions(p_pw text, p_cats text[])
returns table(id bigint, category text, code text, title text, steps jsonb, total int, remaining int, new_round boolean)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
#variable_conflict use_column
declare
  v_seen text[] := '{}';
  v_cat text;
  v_total int;
  v_pick bigint;
  v_code text;
  v_title text;
  v_steps jsonb;
  v_new boolean;
  v_left int;
begin
  -- 先驗密碼（在取得鎖之前），密碼錯誤就不會有任何寫入、也不會卡住鎖
  perform public._assert_pw(p_pw);

  if p_cats is null or coalesce(array_length(p_cats, 1), 0) = 0 then
    raise exception '請至少選一個分類';
  end if;

  -- 同時間只允許一個人抽題，避免兩人抽到同一題
  perform pg_advisory_xact_lock(hashtext('exam_draw_questions'));

  for v_cat in select c from unnest(p_cats) with ordinality as t(c, n) order by n loop
    -- 重複的分類只算一次
    if v_cat is not null and v_cat = any(v_seen) then
      continue;
    end if;
    v_seen := v_seen || coalesce(v_cat, '');

    select count(*)::int into v_total from public.questions q where q.category = v_cat;
    if v_total = 0 then
      raise exception '分類不存在：%', coalesce(v_cat, '(空白)');
    end if;

    v_new := false;

    -- 先從「本輪未抽」挑
    select q.id into v_pick
    from public.questions q
    where q.category = v_cat
      and not exists (select 1 from public.drawn d where d.question_id = q.id)
    order by random()
    limit 1;

    if v_pick is null then
      -- 本輪抽完：清掉該分類已抽記錄，開新一輪（題數>1 時避開上一題）
      delete from public.drawn d
      where d.question_id in (select q.id from public.questions q where q.category = v_cat);
      v_new := true;

      select q.id into v_pick
      from public.questions q
      where q.category = v_cat
        and (v_total = 1
             or q.id is distinct from (select l.question_id from public.category_last l where l.category = v_cat))
      order by random()
      limit 1;
    end if;

    insert into public.drawn (question_id) values (v_pick)
    on conflict (question_id) do update set drawn_at = now();

    insert into public.category_last (category, question_id) values (v_cat, v_pick)
    on conflict (category) do update set question_id = excluded.question_id;

    select q.code, q.title, q.steps into v_code, v_title, v_steps from public.questions q where q.id = v_pick;

    select (v_total - count(*))::int into v_left
    from public.drawn d
    join public.questions q on q.id = d.question_id
    where q.category = v_cat;

    id := v_pick;
    category := v_cat;
    code := v_code;
    title := v_title;
    steps := v_steps;
    total := v_total;
    remaining := v_left;
    new_round := v_new;
    return next;
  end loop;
end;
$$;

-- ---------- 管理函式（需要密碼） ----------

create or replace function public.admin_login(p_pw text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if public._pw_ok(p_pw) then
    return true;
  end if;
  perform pg_sleep(0.5);
  return false;
end;
$$;

create or replace function public.admin_list_questions(p_pw text)
returns table(id bigint, category text, code text, title text, steps jsonb, drawn boolean)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
#variable_conflict use_column
begin
  perform public._assert_pw(p_pw);
  return query
    select q.id, q.category, q.code, q.title, q.steps,
           exists (select 1 from public.drawn d where d.question_id = q.id)
    from public.questions q
    order by min(q.id) over (partition by q.category), q.id;
end;
$$;

create or replace function public.admin_save_question(
  p_pw text, p_id bigint, p_category text, p_code text, p_title text, p_steps jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_cat text := btrim(coalesce(p_category, ''));
  v_code text := nullif(btrim(coalesce(p_code, '')), '');
  v_title text := btrim(coalesce(p_title, ''));
  v_steps jsonb;
  v_n int;
  v_bad int;
  v_old text;
  v_id bigint;
begin
  perform public._assert_pw(p_pw);

  if v_cat = '' then raise exception '分類不可空白'; end if;
  if v_title = '' then raise exception '題組名稱不可空白'; end if;
  if length(v_title) > 100 then raise exception '題組名稱太長（最多 100 字）'; end if;
  if v_code is not null and length(v_code) > 10 then raise exception '代號太長（最多 10 字）'; end if;

  if p_steps is null or jsonb_typeof(p_steps) <> 'array' then
    raise exception '步驟格式不正確，必須是清單';
  end if;
  v_n := jsonb_array_length(p_steps);
  if v_n < 1 then raise exception '至少要有 1 個步驟'; end if;
  if v_n > 30 then raise exception '步驟太多（最多 30 個）'; end if;

  -- 每個步驟必須是物件，action 為非空字串，point 為字串或缺漏
  select count(*) into v_bad
  from jsonb_array_elements(p_steps) e
  where jsonb_typeof(e) <> 'object'
     or jsonb_typeof(e -> 'action') is distinct from 'string'
     or btrim(e ->> 'action') = ''
     or (e ? 'point' and jsonb_typeof(e -> 'point') not in ('string', 'null'));
  if v_bad > 0 then
    raise exception '每個步驟都要有「考官操作」文字，考點必須是文字';
  end if;

  select count(*) into v_bad
  from jsonb_array_elements(p_steps) e
  where length(btrim(e ->> 'action')) > 500
     or length(btrim(coalesce(e ->> 'point', ''))) > 500;
  if v_bad > 0 then
    raise exception '步驟文字太長（考官操作、考點各最多 500 字）';
  end if;

  -- 只保留 action、point 兩個鍵並 trim，依原順序
  select jsonb_agg(jsonb_build_object(
           'action', btrim(e.v ->> 'action'),
           'point', btrim(coalesce(e.v ->> 'point', ''))) order by e.n)
    into v_steps
  from jsonb_array_elements(p_steps) with ordinality as e(v, n);

  if p_id is null then
    insert into public.questions (category, code, title, steps)
    values (v_cat, v_code, v_title, v_steps)
    returning id into v_id;
    return v_id;
  end if;

  select q.category into v_old from public.questions q where q.id = p_id for update;
  if not found then
    raise exception '找不到題目：%', p_id;
  end if;

  update public.questions
     set category = v_cat, code = v_code, title = v_title, steps = v_steps
   where id = p_id;

  -- 換分類時，把這題從已抽記錄移除，避免記錄錯亂
  if v_old is distinct from v_cat then
    delete from public.drawn where question_id = p_id;
  end if;

  return p_id;
end;
$$;

create or replace function public.admin_delete_question(p_pw text, p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  perform public._assert_pw(p_pw);
  delete from public.questions where id = p_id; -- drawn 由 cascade 一併清除
end;
$$;

create or replace function public.admin_rename_category(p_pw text, p_old text, p_new text)
returns integer
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_new text := btrim(coalesce(p_new, ''));
  v_count integer;
begin
  perform public._assert_pw(p_pw);

  if v_new = '' then raise exception '新分類名稱不可空白'; end if;

  update public.questions set category = v_new where category = p_old;
  get diagnostics v_count = row_count;

  -- 舊分類的「最近一題」記錄刪掉即可
  if p_old is distinct from v_new then
    delete from public.category_last where category = p_old;
  end if;

  return v_count;
end;
$$;

create or replace function public.admin_reset(p_pw text, p_category text)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  perform public._assert_pw(p_pw);

  if p_category is null then
    delete from public.drawn where true;
    delete from public.category_last where true;
  else
    delete from public.drawn
    where question_id in (select q.id from public.questions q where q.category = p_category);
    delete from public.category_last where category = p_category;
  end if;
end;
$$;

