-- ============================================================
-- 設定（或更換）管理密碼
--
-- 怎麼用：
--   1. 先把下面引號裡的「在這裡填你的密碼」改成你要的密碼（至少 8 碼）
--   2. 貼到 Supabase 的 SQL Editor → Run
--   3. 執行完，不要把這個檔案存著真實密碼：把引號內文字改回「在這裡填你的密碼」再存檔
--
-- 要換密碼就再跑一次（會覆蓋舊的）。資料庫只存加密後的雜湊，不存原始密碼。
-- 注意：請先執行過 schema.sql 再執行這個檔案。
-- ============================================================

insert into app_secret (id, pw_hash) values (1, extensions.crypt('在這裡填你的密碼', extensions.gen_salt('bf')))
on conflict (id) do update set pw_hash = excluded.pw_hash;
